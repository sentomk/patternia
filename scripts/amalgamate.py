#!/usr/bin/env python3
"""Generate the single-header build of Patternia.

Starts at ``include/ptn/patternia.hpp`` and inlines every Patternia
header it includes, depth first, so the result has the same content in
the same order as the compiler sees it through ``include/``. Each
header is inlined once (every Patternia header uses ``#pragma once``),
standard library includes are kept as they are, and the result gets a
single ``#pragma once`` and a banner with the version and license.

Usage:

    python3 scripts/amalgamate.py            # write single_include/
    python3 scripts/amalgamate.py --check    # fail if it is stale
    python3 scripts/amalgamate.py -o out.hpp # write elsewhere

Patternia headers are included with quotes (``"ptn/..."`` or a path
relative to the including file); anything else is left alone. The
script fails on a quoted include it cannot resolve, so a new header
can never be dropped silently.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INCLUDE_DIR = ROOT / "include"
ENTRY = INCLUDE_DIR / "ptn" / "patternia.hpp"
DEFAULT_OUTPUT = ROOT / "single_include" / "ptn" / "patternia.hpp"

QUOTED_INCLUDE = re.compile(r'^\s*#\s*include\s*"([^"]+)"')
PRAGMA_ONCE = re.compile(r"^\s*#\s*pragma\s+once\b")
IWYU_PRAGMA = re.compile(r"^\s*//\s*IWYU pragma:")
PROJECT_VERSION = re.compile(
    r"project\(\s*patternia\b[^)]*?\bVERSION\s+([0-9][0-9.]*)", re.S
)


def project_version() -> str:
    text = (ROOT / "CMakeLists.txt").read_text(encoding="utf-8")
    match = PROJECT_VERSION.search(text)
    if not match:
        sys.exit("amalgamate: cannot find the project VERSION in CMakeLists.txt")
    return match.group(1)


def banner(version: str) -> str:
    return f"""\
// Patternia {version}: single-header build.
// https://github.com/sentomk/patternia
//
// SPDX-License-Identifier: MIT
// Copyright (c) 2026 sentomk. See LICENSE in the repository.
//
// Generated by scripts/amalgamate.py from include/. Do not edit this
// file; edit the headers under include/ptn/ and run
//   python3 scripts/amalgamate.py

#pragma once
"""


def resolve(name: str, including: Path) -> Path:
    for candidate in (including.parent / name, INCLUDE_DIR / name):
        if candidate.is_file():
            return candidate.resolve()
    rel = including.relative_to(INCLUDE_DIR)
    sys.exit(f'amalgamate: {rel}: cannot resolve #include "{name}"')


def amalgamate() -> str:
    seen: set[Path] = set()
    out: list[str] = [banner(project_version())]

    def emit(path: Path) -> None:
        if path in seen:
            return
        seen.add(path)
        rel = path.relative_to(INCLUDE_DIR).as_posix()
        out.append(f"\n// ---- begin {rel} ----\n")
        for line in path.read_text(encoding="utf-8").splitlines(True):
            include = QUOTED_INCLUDE.match(line)
            if include:
                emit(resolve(include.group(1), path))
                continue
            if PRAGMA_ONCE.match(line) or IWYU_PRAGMA.match(line):
                continue
            out.append(line if line.endswith("\n") else line + "\n")
        out.append(f"// ---- end {rel} ----\n")

    emit(ENTRY.resolve())
    return "".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="where to write the header (default: %(default)s)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 if the output file is out of date",
    )
    args = parser.parse_args()

    text = amalgamate()
    output: Path = args.output

    if args.check:
        current = output.read_text(encoding="utf-8") if output.is_file() else None
        if current != text:
            print(
                f"amalgamate: {output} is out of date; "
                "run python3 scripts/amalgamate.py and commit the result",
                file=sys.stderr,
            )
            return 1
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.is_file() or output.read_text(encoding="utf-8") != text:
        output.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
